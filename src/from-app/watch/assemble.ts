// F57: the files of a downloaded contract watcher. Pure: the runtime bundle comes in as text.
import { WatchContracts } from './runtime/types';

export interface WatcherFile { path: string; content: string }

/** user text in a `//` line comment: no line breaks, no `*\/` */
const inComment = (s: string) => String(s).replace(/[\r\n\u2028\u2029]+/g, ' ').replace(/\*\//g, '* /');

/** rabbinatix-watch.js: the runtime, this system's contracts, and `watchContracts` bound to them */
export function watcherModule(c: WatchContracts, runtimeJs: string): string {
  return `// Rabbinatix contract watcher for ${inComment(c.system.name)} (${inComment(c.org.name)})
// Contracts from ${inComment(c.generatedAt)} · fingerprint ${inComment(c.fingerprint)} · ${c.apis.length} API${c.apis.length === 1 ? '' : 's'}
// Generated by Rabbinatix${c.link ? `: ${inComment(c.link)}` : ''}. Use it in development only; see README.md.
// Download again when the contracts change (Rabbinatix tells you on the system page).

${runtimeJs.trim()}

const CONTRACTS = ${JSON.stringify(c, null, 2)};

/** Start the watcher with the contracts in this file. Call it once, in development, before the app makes requests. */
export function watchContracts(options) {
  return createWatcher(CONTRACTS, options);
}
export { CONTRACTS as contracts };
`;
}

const hostRows = (c: WatchContracts, systemName: (id: string) => string) =>
  Object.entries(c.hosts).length
    ? Object.entries(c.hosts).map(([h, id]) => `| \`${h}\` | ${systemName(id)} (\`${id}\`) |`).join('\n')
    : '| _(none yet)_ | APIs match calls to the page\'s own origin only |';

