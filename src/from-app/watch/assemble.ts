/** the terminal command the phone SDKs send their calls to */
export const LISTEN_COMMAND = 'npx -y rabbinatix watch listen';

export function watcherReadme(c: WatchContracts, phone = false): string {
  const providers = new Map(c.apis.map((a) => [a.provider.id, a.provider.name]));
  const name = (id: string) => providers.get(id) ?? id;
  const example = c.apis.find((a) => a.provides) ?? c.apis[0];
  const hostsExample = Object.keys(c.hosts).length
    ? JSON.stringify(c.hosts).replace(/,/g, ', ').replace(/:/g, ': ')
    : `{ '/': '${example?.provider.id ?? 'my-api'}' }`;
  return `# Rabbinatix contract watcher · ${c.system.name}

Checks every API call **${c.system.name}** makes against its contracts in Rabbinatix, while you develop, and reports
drift in the console and on the page. Contracts from ${c.generatedAt.slice(0, 10)} (${c.apis.length} API${c.apis.length === 1 ? '' : 's'}, fingerprint \`${c.fingerprint}\`).

Files:
- \`rabbinatix-watch.js\`: the watcher and these contracts, one ES module with no dependencies
- \`rabbinatix-watch.d.ts\`: types for TypeScript projects
- \`README.md\`: this file${phone ? `
- \`phone/\`: the same checks for phone apps (Android, iOS, Flutter, React Native); see section 9` : ''}

## 1. Add it to your project
Put both files in a development-only folder, for example \`src/dev/\`. Commit them (the team shares one copy) or add
the folder to \`.gitignore\` (each developer downloads their own).

## 2. Start it before your app makes requests, in development only
The dynamic \`import()\` inside a dev-only branch keeps the watcher out of production builds.

**Angular** (\`src/main.ts\`)
\`\`\`ts
import { bootstrapApplication } from '@angular/platform-browser';
import { appConfig } from './app/app.config';
import { AppComponent } from './app/app.component';

async function start() {
  // ngDevMode is false in production builds, so this branch and the watcher are left out of them
  if (typeof ngDevMode === 'undefined' || ngDevMode) {
    const { watchContracts } = await import('./dev/rabbinatix-watch.js');
    watchContracts();
  }
  await bootstrapApplication(AppComponent, appConfig);
}
start();
\`\`\`

**React / Vue / Svelte with Vite** (\`src/main.tsx\` or \`src/main.ts\`)
\`\`\`ts
if (import.meta.env.DEV) {
  const { watchContracts } = await import('./dev/rabbinatix-watch.js');
  watchContracts();
}
// …then render your app as usual
\`\`\`

**Next.js** (\`instrumentation-client.ts\` at the project root, Next 15.3+)
\`\`\`ts
if (process.env.NODE_ENV === 'development') {
  import('./src/dev/rabbinatix-watch.js').then(({ watchContracts }) => watchContracts());
}
\`\`\`

**Plain HTML**
\`\`\`html
<script type="module">
  import { watchContracts } from './dev/rabbinatix-watch.js';
  watchContracts();
</script>
\`\`\`

You should see \`Rabbinatix watcher · ${c.system.name} · ${c.apis.length} APIs · contracts from ${c.generatedAt.slice(0, 10)}\` in the console.

## 3. Hosts
Which API origin belongs to which system. Calls to a mapped host are only matched against that system's APIs.
Calls to hosts that aren't listed (analytics, CDNs, other APIs) are not checked; calls to the page's own origin match
by path. Calls to a provider's test server in Rabbinatix are checked too, with no host to add.

| Host | System |
|---|---|
${hostRows(c, name)}

Change them without downloading again: \`watchContracts({ hosts: ${hostsExample} })\`. \`'/'\` means the page's own origin.

## 4. Options (all optional)
\`\`\`ts
watchContracts({
  hosts: ${hostsExample},  // origin/host → system; overrides the table above
  warnOn: 'warning',          // report 'breaking' | 'warning' | 'info' and above (default 'warning')
  failOn: 'never',            // 'breaking' makes window.__rabbinatix.failed() true, for tests (default 'never')
  report: ['console', 'overlay'], // where findings go (default both)
  ignore: ['/api/*/metrics', /\\/health$/], // calls never checked (path globs or RegExps on the URL)
  sample: 1,                  // share of calls checked, 0–1 (default 1)
  maxBodyBytes: 1_000_000,    // larger bodies are skipped (default 1 MB)
  undeclared: true,           // report calls to known hosts that match no contract, as info (default true)
  onFinding: (f) => {},       // your own handler
});
\`\`\`
\`watchContracts()\` returns \`{ stop(), findings(), clear(), failed() }\`. \`stop()\` puts \`fetch\` and \`XMLHttpRequest\` back.

## 5. Read the findings
- **Console**: one message per call and new problem (repeats are counted, not repeated).
- **Overlay**: a badge in the bottom-right corner, red for breaking, amber for warnings. Click it for the list; each
  item links to the contract in Rabbinatix. **Hide** until the next finding; **Clear** resets.
- **In code**: \`window.__rabbinatix.findings()\`, \`.clear()\`, \`.failed()\`.

| Finding | Meaning | Usually fix |
|---|---|---|
| Required field missing | Your contract needs it; the response did not have it | The backend, or mark it optional in Rabbinatix |
| Wrong type / null not allowed | e.g. \`"true"\` where boolean was expected | The backend, or the contract if the frontend copes |
| Status not declared | e.g. a 409 nobody declared | Declare the response in Rabbinatix and handle it in the UI |
| [provider's spec] | The backend's own declaration doesn't match what it returns | The backend updates its spec (OpenAPI import) |
| Request: required query/header/auth missing | You don't send what the provider requires | The frontend call, or the provider's declaration |
| No contract covers this call (info) | A request to a known host that matches no contract | Declare it in Rabbinatix, or \`ignore\` it |
| Not in your contract (info) | The provider added a field | Nothing, or declare it to use it |

Values stay in your browser: checks work on shapes, and nothing is sent anywhere.

## 6. Use it in end-to-end tests
Start the app with \`watchContracts({ failOn: 'breaking' })\` in the test environment, then fail the test on findings:
\`\`\`ts
// Playwright
test.afterEach(async ({ page }) => {
  const failed = await page.evaluate(() => (window as any).__rabbinatix?.failed?.() ?? false);
  const findings = await page.evaluate(() => (window as any).__rabbinatix?.findings?.() ?? []);
  expect(failed, JSON.stringify(findings, null, 2)).toBe(false);
});
\`\`\`

## 7. Keep it up to date
Rabbinatix shows **"Contracts changed since your last download"** on ${c.system.name}'s page${c.link ? ` (${c.link})` : ''} when an
API it consumes changes. Download again and replace the two files.

## 8. Troubleshooting
- **No start message**: the import didn't run. Check the dev-only condition and the file path.
- **No findings at all**: check \`hosts\` (the origin of your API calls should map to a system) and \`ignore\`.
- **"No contract covers this call" for an API you declared**: the path template differs (\`/users/{id}\` vs
  \`/user/{id}\`), or the host maps to another system.
- **Too noisy**: \`warnOn: 'breaking'\`, or \`ignore\` paths you don't own.
- **Streaming, files, non-JSON**: skipped on purpose; only JSON bodies are checked.
- **Production**: after a production build, \`grep -r rabbinatix-watch dist/\` finds nothing when the import is dev-only.
${phone ? phoneReadme() : ''}`;
}

function phoneReadme(): string {
  return `
## 9. Phone apps
A phone app sends each call it makes to your computer, and \`rabbinatix watch listen\` checks it there with these
contracts, like the browser watcher. What your app sends and receives stays on your computer; findings go to Rabbinatix
as the browser watcher's do (\`--no-share\` keeps them in the terminal).

1. In a terminal, next to \`rabbinatix-watch.js\` (Node.js 20 or later):
   \`\`\`sh
   ${LISTEN_COMMAND}
   \`\`\`
   Findings print there as calls come in. Stop it with Ctrl+C for a summary.
2. Copy the file for your platform from \`phone/\` into your app and start it in debug builds only:

${PHONE_STARTS.map((p) => `**${p.label}** (\`${p.file}\`)
\`\`\`
${p.code}
\`\`\``).join('\n\n')}

The Android emulator reaches your computer at \`10.0.2.2\`, the iOS simulator at \`127.0.0.1\`: that is the default.
A phone on your network: start the listener with \`--host 0.0.0.0\`, and give the SDK your computer's address and the
code the terminal shows (for example \`RabbinatixWatch("http://192.168.1.20:4012", code = "…")\`).

Android debug builds must allow plain HTTP to your computer. Add \`res/xml/network_security_config.xml\` in the
\`debug\` source set only:
\`\`\`xml
<network-security-config>
  <domain-config cleartextTrafficPermitted="true">
    <domain includeSubdomains="false">10.0.2.2</domain>
  </domain-config>
</network-security-config>
\`\`\`
and \`android:networkSecurityConfig="@xml/network_security_config"\` on \`<application>\` in the debug manifest. iOS allows
\`127.0.0.1\` already; a phone on your network needs \`NSAllowsLocalNetworking\` in the debug Info.plist.

**Backends and OpenTelemetry**: a service already traced with OpenTelemetry can send its traces to the listener
instead: \`OTEL_EXPORTER_OTLP_ENDPOINT=http://127.0.0.1:4012\` (protobuf or JSON, gzipped or not). Traces hold no
bodies, so they check status codes, calls nobody declared and, when the SDK records headers, required headers.
Trace files from a collector's file exporter (JSON or proto): \`npx -y rabbinatix watch import traces.json\`.
`;
}

export function watcherFiles(c: WatchContracts, runtimeJs: string, dts: string, phone: { name: string; content: string }[] = []): WatcherFile[] {
  return [
    { path: 'rabbinatix-watch.js', content: watcherModule(c, runtimeJs) },
    { path: 'rabbinatix-watch.d.ts', content: dts },
    { path: 'README.md', content: watcherReadme(c, phone.length > 0) },
    ...phone.map((f) => ({ path: `phone/${f.name}`, content: f.content })),
  ];
}
